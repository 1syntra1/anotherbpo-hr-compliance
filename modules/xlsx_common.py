"""Shared styling and header block for generated Excel reports."""
import io

from openpyxl import Workbook
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

from modules.xlsx_safe import neutralise_workbook

NAVY = "1A2744"
LIGHT_BLUE = "D9E8F5"
HEADER_BLUE = "2D9CDB"
WHITE = "FFFFFF"
GREY = "F2F2F2"
AMBER = "FFF3CD"
MONEY = '#,##0.00'

_thin = Side(style="thin")
BORDER = Border(left=_thin, right=_thin, top=_thin, bottom=_thin)


def fill(hex_color):
    return PatternFill("solid", fgColor=hex_color)


def new_workbook(title):
    wb = Workbook()
    ws = wb.active
    ws.title = title[:31]
    return wb, ws


def title_block(ws, title, subtitle, width_cols, meta, row=1):
    """Title rows plus a label/value block. `meta` is a list of (label, value).
    Returns the next free row."""
    last = get_column_letter(width_cols)
    ws.merge_cells("A%d:%s%d" % (row, last, row))
    c = ws.cell(row=row, column=1, value=title)
    c.font = Font(bold=True, size=14, color=WHITE)
    c.fill = fill(NAVY)
    c.alignment = Alignment(horizontal="center", vertical="center")
    ws.row_dimensions[row].height = 30
    row += 1
    if subtitle:
        ws.merge_cells("A%d:%s%d" % (row, last, row))
        c = ws.cell(row=row, column=1, value=subtitle)
        c.font = Font(italic=True, size=10, color=WHITE)
        c.fill = fill(HEADER_BLUE)
        c.alignment = Alignment(horizontal="center")
        row += 1
    row += 1
    for label, value in meta:
        a = ws.cell(row=row, column=1, value=label)
        a.font = Font(bold=True)
        a.fill = fill(LIGHT_BLUE)
        a.border = BORDER
        b = ws.cell(row=row, column=2, value=value)
        b.border = BORDER
        if width_cols > 2:
            ws.merge_cells(start_row=row, start_column=2, end_row=row, end_column=min(width_cols, 6))
        row += 1
    return row + 1


def warning_row(ws, row, text, width_cols):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=width_cols)
    c = ws.cell(row=row, column=1, value=text)
    c.font = Font(bold=True, color="7A4B00")
    c.fill = fill(AMBER)
    c.alignment = Alignment(wrap_text=True, vertical="center")
    ws.row_dimensions[row].height = 32
    return row + 2


def header_row(ws, row, headers, start_col=1, color=HEADER_BLUE):
    for i, h in enumerate(headers):
        c = ws.cell(row=row, column=start_col + i, value=h)
        c.font = Font(bold=True, color=WHITE)
        c.fill = fill(color)
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)
        c.border = BORDER
    ws.row_dimensions[row].height = 30
    return row + 1


def data_row(ws, row, values, money_cols=(), bold=False, shade=False, total=False):
    for i, v in enumerate(values, 1):
        c = ws.cell(row=row, column=i, value=v)
        c.border = BORDER
        if i in money_cols:
            c.number_format = MONEY
        if i > 1:
            c.alignment = Alignment(horizontal="right" if isinstance(v, (int, float)) else "left")
        if total:
            c.font = Font(bold=True, color=WHITE)
            c.fill = fill(NAVY)
        elif bold:
            c.font = Font(bold=True)
        if shade and not total:
            c.fill = fill(GREY)
    return row + 1


def widths(ws, values):
    for i, w in enumerate(values, 1):
        ws.column_dimensions[get_column_letter(i)].width = w


def report_meta(ctx):
    """Standard traceability lines every stored report carries."""
    meta = [
        ("Report version:", ctx.get("version_label", "Preview (not stored)")),
        ("Generated:", ctx.get("generated_at", "")),
        ("Generated by:", ctx.get("generated_by", "")),
        ("Rule set:", ctx.get("rule_label", "")),
        ("Source data fingerprint:", (ctx.get("snapshot_sha256") or "")[:16]),
    ]
    return meta


def save(wb, properties_time=None):
    neutralise_workbook(wb)
    if properties_time is not None:
        wb.properties.created = properties_time
        wb.properties.modified = properties_time
    out = io.BytesIO()
    wb.save(out)
    return out.getvalue()
